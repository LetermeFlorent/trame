#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Special {
    Dashed(u8),
    Arc,
    Diagonal { rising: bool, falling: bool },
}

pub fn special(ch: char) -> Option<Special> {
    Some(match u32::from(ch) {
        0x2504..=0x2507 => Special::Dashed(3),
        0x2508..=0x250B => Special::Dashed(4),
        0x254C..=0x254F => Special::Dashed(2),
        0x256D..=0x2570 => Special::Arc,
        0x2571 => Special::Diagonal {
            rising: true,
            falling: false,
        },
        0x2572 => Special::Diagonal {
            rising: false,
            falling: true,
        },
        0x2573 => Special::Diagonal {
            rising: true,
            falling: true,
        },
        _ => return None,
    })
}

pub fn line_code(ch: char) -> Option<u16> {
    let index = u32::from(ch).checked_sub(FIRST)?;
    LINES.get(usize::try_from(index).ok()?).copied()
}
